export function createStoryPanelOutsideDismissHandler({ panel, onDismiss } = {}) {
  if (!panel?.contains || typeof onDismiss !== 'function') throw new TypeError('STORY_RUNTIME_DISMISS_INPUT_INVALID');
  return function dismissStoryPanelFromOutside(event) {
    if (panel.hidden || panel.contains(event?.target)) return false;
    event?.preventDefault?.();
    event?.stopPropagation?.();
    event?.stopImmediatePropagation?.();
    onDismiss();
    return true;
  };
}

export function mountStoryFirstSceneRuntime(host) {
  validateHost(host);
  const documentSource = host.document || globalThis.document;
  if (!documentSource?.createElement) throw new TypeError('STORY_RUNTIME_DOCUMENT_REQUIRED');
  const home = documentSource.querySelector('.screen.home[data-screen="home"]');
  const app = documentSource.querySelector('.app');
  if (!home || !app) throw new Error('STORY_RUNTIME_SURFACE_MISSING');
  if (globalThis[GLOBAL_KEY]?.getSnapshot) return globalThis[GLOBAL_KEY];

  installStyle(documentSource);
  const controller = createStoryFirstSceneController({ host });
  const entry = element(documentSource, 'button', {
    type: 'button',
    class: 'storyFirstSceneEntry',
    'data-story-action': 'open',
    'aria-haspopup': 'dialog',
  }, '物語');
  const panel = element(documentSource, 'section', {
    class: 'storyFirstScenePanel',
    'data-story-scene': STORY_FIRST_SCENE_IDENTITY.sceneId,
    role: 'dialog',
    'aria-modal': 'true',
    'aria-labelledby': 'storyFirstSceneTitle',
  });
  panel.hidden = true;
  panel.innerHTML = `
    <header class="storyFirstSceneHead">
      <div>
        <h2 id="storyFirstSceneTitle">アロンダイトの輝き</h2>
        <p>月光の夜</p>
      </div>
      <button type="button" class="storyFirstSceneAction" data-story-action="close" aria-label="閉じる">閉じる</button>
    </header>
    <p class="storyFirstSceneText" data-story-line></p>
    <div class="storyFirstSceneActions">
      <button type="button" class="storyFirstSceneAction" data-story-action="skip">スキップ</button>
      <button type="button" class="storyFirstSceneAction primary" data-story-action="next">次へ</button>
    </div>
  `;
  home.append(entry);
  app.append(panel);

  const line = panel.querySelector('[data-story-line]');
  const nextButton = panel.querySelector('[data-story-action="next"]');

  function render(snapshot = controller.getSnapshot()) {
    panel.hidden = !snapshot.opened;
    if (snapshot.opened) {
      line.textContent = snapshot.line;
      const atLastLine = snapshot.cursor >= STORY_FIRST_SCENE_LINES.length - 1;
      nextButton.textContent = atLastLine ? '閉じる' : '次へ';
    }
    return snapshot;
  }

  function open() {
    return render(controller.open());
  }

  function close() {
    return render(controller.close());
  }

  function next() {
    return render(controller.next());
  }

  function skip() {
    return render(controller.skip());
  }

  entry.addEventListener('click', open);
  panel.querySelector('[data-story-action="close"]').addEventListener('click', close);
  panel.querySelector('[data-story-action="skip"]').addEventListener('click', skip);
  nextButton.addEventListener('click', next);

  const dismissOnOutsideClick = createStoryPanelOutsideDismissHandler({ panel, onDismiss: close });
  documentSource.addEventListener('click', dismissOnOutsideClick, true);
  const dismissOnEscape = (event) => {
    if (event?.key !== 'Escape' || panel.hidden) return;
    event.preventDefault?.();
    close();
  };
  documentSource.addEventListener('keydown', dismissOnEscape);

  const runtime = Object.freeze({
    open,
    close,
    next,
    skip,
    getSnapshot: controller.getSnapshot,
    destroy() {
      documentSource.removeEventListener('click', dismissOnOutsideClick, true);
      documentSource.removeEventListener('keydown', dismissOnEscape);
      entry.remove();
      panel.remove();
      if (globalThis[GLOBAL_KEY] === runtime) delete globalThis[GLOBAL_KEY];
    },
  });
  globalThis[GLOBAL_KEY] = runtime;
  return runtime;
}

export function createCurrentBrowserStoryHost({
  qa = globalThis.__GAMEROAD_TEST__,
  documentSource = globalThis.document,
} = {}) {
  if (!qa?.state || !documentSource) return null;
  return Object.freeze({
    document: documentSource,
    readStoryProgress() {
      return cloneJson(qa.state.storyProgress ?? null);
    },
    writeStoryProgress(next) {
      qa.state.storyProgress = cloneJson(next);
      return cloneJson(qa.state.storyProgress);
    },
  });
}

export function mountStoryFirstSceneFromCurrentBrowser(options = {}) {
  if (globalThis[GLOBAL_KEY]?.getSnapshot) return globalThis[GLOBAL_KEY];
  const host = createCurrentBrowserStoryHost(options);
  if (!host) return null;
  return mountStoryFirstSceneRuntime(host);
}

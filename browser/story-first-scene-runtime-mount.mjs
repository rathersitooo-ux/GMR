const PROGRESS_SCHEMA_VERSION = 'gameroad.story-progress.r1';
const GLOBAL_KEY = 'GAMEROAD_STORY_RUNTIME';
const STYLE_ID = 'gameroad-story-first-scene-r1-style';

function cloneJson(value) {
  if (value === undefined) return undefined;
  return JSON.parse(JSON.stringify(value));
}

function sameIdentity(value) {
  return Boolean(
    value
    && value.storyId === STORY_FIRST_SCENE_IDENTITY.storyId
    && value.chapterId === STORY_FIRST_SCENE_IDENTITY.chapterId
    && value.sceneId === STORY_FIRST_SCENE_IDENTITY.sceneId
    && value.canonVersion === STORY_FIRST_SCENE_IDENTITY.canonVersion
  );
}

export function createDefaultStoryProgress() {
  return Object.freeze({
    schemaVersion: PROGRESS_SCHEMA_VERSION,
    ...STORY_FIRST_SCENE_IDENTITY,
    read: false,
    currentPosition: 0,
  });
}

export function normalizeStoryProgress(value) {
  if (!value || value.schemaVersion !== PROGRESS_SCHEMA_VERSION || !sameIdentity(value)) {
    return createDefaultStoryProgress();
  }
  const numericPosition = Number(value.currentPosition);
  const currentPosition = Number.isInteger(numericPosition)
    ? Math.max(0, Math.min(STORY_FIRST_SCENE_LINES.length, numericPosition))
    : 0;
  const read = Boolean(value.read) || currentPosition >= STORY_FIRST_SCENE_LINES.length;
  return Object.freeze({
    schemaVersion: PROGRESS_SCHEMA_VERSION,
    ...STORY_FIRST_SCENE_IDENTITY,
    read,
    currentPosition: read ? STORY_FIRST_SCENE_LINES.length : currentPosition,
  });
}

function validateHost(host) {
  if (!host || typeof host.readStoryProgress !== 'function' || typeof host.writeStoryProgress !== 'function') {
    throw new TypeError('STORY_RUNTIME_HOST_REQUIRED');
  }
  return host;
}

function progressBytes(progress) {
  return JSON.stringify(progress);
}

export function createStoryFirstSceneController({ host } = {}) {
  validateHost(host);
  let progress = createDefaultStoryProgress();
  let cursor = 0;
  let opened = false;

  const snapshot = () => Object.freeze({
    opened,
    cursor,
    lineCount: STORY_FIRST_SCENE_LINES.length,
    line: STORY_FIRST_SCENE_LINES[Math.min(cursor, STORY_FIRST_SCENE_LINES.length - 1)] || '',
    progress,
  });

  function load() {
    progress = normalizeStoryProgress(host.readStoryProgress());
    cursor = progress.read ? 0 : progress.currentPosition;
    return snapshot();
  }

  function persist(next) {
    const normalized = normalizeStoryProgress(next);
    host.writeStoryProgress(cloneJson(normalized));
    const readback = normalizeStoryProgress(host.readStoryProgress());
    if (progressBytes(readback) !== progressBytes(normalized)) {
      throw new Error('STORY_RUNTIME_PROGRESS_READBACK_MISMATCH');
    }
    progress = readback;
    return progress;
  }

  function open() {
    load();
    opened = true;
    return snapshot();
  }

  function close() {
    opened = false;
    return snapshot();
  }

  function next() {
    if (!opened) throw new Error('STORY_RUNTIME_NOT_OPEN');
    const nextCursor = Math.min(STORY_FIRST_SCENE_LINES.length, cursor + 1);
    cursor = nextCursor;
    if (!progress.read) {
      persist({
        ...progress,
        currentPosition: nextCursor,
        read: nextCursor >= STORY_FIRST_SCENE_LINES.length,
      });
    }
    if (cursor >= STORY_FIRST_SCENE_LINES.length) opened = false;
    return snapshot();
  }

  function skip() {
    if (!opened) throw new Error('STORY_RUNTIME_NOT_OPEN');
    cursor = STORY_FIRST_SCENE_LINES.length;
    if (!progress.read) {
      persist({
        ...progress,
        currentPosition: STORY_FIRST_SCENE_LINES.length,
        read: true,
      });
    }
    opened = false;
    return snapshot();
  }

  return Object.freeze({
    open,
    close,
    next,
    skip,
    getSnapshot: snapshot,
  });
}

function element(documentSource, tag, attributes = {}, text = '') {
  const node = documentSource.createElement(tag);
  for (const [name, value] of Object.entries(attributes)) {
    if (name === 'class') node.className = value;
    else node.setAttribute(name, value);
  }
  node.textContent = text;
  return node;
}


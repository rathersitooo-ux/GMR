import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const SOURCE_PATH = path.join(ROOT, 'browser', 'board-facility-state-core.mjs');
const OUTPUT_PATH = path.join(ROOT, 'browser', 'board-facility-state-core.classic.js');
const GLOBAL_NAME = 'GAMEROAD_BOARD_FACILITY_STATE_CORE';
const BRIDGE_VERSION = 'gameroad.board-facility-classic-bridge.v1';

function collectExports(source) {
  const found = [];
  const patterns = [
    { kind: 'function', regex: /\bexport\s+(?:async\s+)?function\s+([A-Za-z_$][\w$]*)/g },
    { kind: 'value', regex: /\bexport\s+(?:const|let|var|class)\s+([A-Za-z_$][\w$]*)/g },
  ];
  for (const { kind, regex } of patterns) {
    for (const match of source.matchAll(regex)) {
      found.push({ kind, name: match[1], index: match.index ?? Number.MAX_SAFE_INTEGER });
    }
  }
  if (/\bexport\s+(?:default|\{)/.test(source)) {
    throw new Error('BOARD_FACILITY_CLASSIC_UNSUPPORTED_EXPORT_FORM');
  }
  found.sort((a, b) => a.index - b.index);
  const names = found.map(entry => entry.name);
  if (names.length === 0 || new Set(names).size !== names.length) {
    throw new Error('BOARD_FACILITY_CLASSIC_EXPORT_SURFACE_INVALID');
  }
  return found;
}

function renderBridge(exports) {
  const functionNames = exports.filter(entry => entry.kind === 'function').map(entry => entry.name);
  const valueNames = exports.filter(entry => entry.kind === 'value').map(entry => entry.name);
  const methodLines = functionNames.map(name =>
    `    ${name}(...args) { return requireCore().${name}(...args); },`
  ).join('\n');
  const getterLines = valueNames.map(name =>
    `  Object.defineProperty(api, ${JSON.stringify(name)}, { enumerable: true, get() { return requireCore().${name}; } });`
  ).join('\n');
  const expected = exports.map(entry => JSON.stringify(entry.name)).join(', ');

  return `// AUTO-GENERATED by scripts/build-board-facility-classic.mjs. DO NOT EDIT.\n` +
`// Source of truth: browser/board-facility-state-core.mjs\n` +
`(function installBoardFacilityClassicBridge(global) {\n` +
`  'use strict';\n` +
`  const GLOBAL_NAME = ${JSON.stringify(GLOBAL_NAME)};\n` +
`  const BRIDGE_VERSION = ${JSON.stringify(BRIDGE_VERSION)};\n` +
`  const EXPECTED_EXPORTS = Object.freeze([${expected}]);\n` +
`  if (!global || (typeof global !== 'object' && typeof global !== 'function')) {\n` +
`    throw new Error('BOARD_FACILITY_GLOBAL_REQUIRED');\n` +
`  }\n` +
`  if (Object.prototype.hasOwnProperty.call(global, GLOBAL_NAME)) {\n` +
`    const existing = global[GLOBAL_NAME];\n` +
`    if (existing && existing.bridgeVersion === BRIDGE_VERSION) return;\n` +
`    throw new Error('BOARD_FACILITY_GLOBAL_COLLISION');\n` +
`  }\n` +
`  let core = null;\n` +
`  let loadError = null;\n` +
`  function requireCore() {\n` +
`    if (core) return core;\n` +
`    if (loadError) {\n` +
`      const error = new Error('BOARD_FACILITY_CORE_LOAD_FAILED');\n` +
`      error.cause = loadError;\n` +
`      throw error;\n` +
`    }\n` +
`    throw new Error('BOARD_FACILITY_CORE_NOT_READY');\n` +
`  }\n` +
`  const api = {\n` +
`    bridgeVersion: BRIDGE_VERSION,\n` +
`    expectedExports: EXPECTED_EXPORTS,\n` +
`    isReady() { return core !== null; },\n` +
`${methodLines}\n` +
`  };\n` +
`${getterLines}${getterLines ? '\n' : ''}` +
`  const ready = import('./board-facility-state-core.mjs').then(namespace => {\n` +
`    for (const name of EXPECTED_EXPORTS) {\n` +
`      if (!Object.prototype.hasOwnProperty.call(namespace, name)) {\n` +
`        throw new Error('BOARD_FACILITY_CORE_EXPORT_MISSING:' + name);\n` +
`      }\n` +
`    }\n` +
`    core = namespace;\n` +
`    return api;\n` +
`  }).catch(error => {\n` +
`    loadError = error;\n` +
`    throw error;\n` +
`  });\n` +
`  Object.defineProperty(api, 'ready', { enumerable: true, value: ready });\n` +
`  Object.freeze(api);\n` +
`  Object.defineProperty(global, GLOBAL_NAME, {\n` +
`    configurable: false,\n` +
`    enumerable: true,\n` +
`    writable: false,\n` +
`    value: api,\n` +
`  });\n` +
`})(globalThis);\n`;
}

const source = fs.readFileSync(SOURCE_PATH, 'utf8');
const output = renderBridge(collectExports(source));
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUTPUT_PATH) ? fs.readFileSync(OUTPUT_PATH, 'utf8') : '';
  if (current !== output) {
    console.error('board facility classic bridge is stale; run: node scripts/build-board-facility-classic.mjs');
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(OUTPUT_PATH, output);
}
